require('dotenv').config();

const express = require('express');
const { Pool } = require('pg');

const app = express();
app.use(express.json());

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.DB_SSL === 'true' ? { rejectUnauthorized: false } : false,
});

async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS animes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      titulo TEXT NOT NULL,
      genero TEXT NOT NULL,
      anio INTEGER,
      descripcion TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await pool.query(`
    INSERT INTO animes (titulo, genero, anio, descripcion)
    SELECT seed.titulo, seed.genero, seed.anio, seed.descripcion
    FROM (VALUES
      ('Fullmetal Alchemist: Brotherhood', 'Aventura, fantasía', 2009, 'Dos hermanos buscan la piedra filosofal para recuperar lo que perdieron.'),
      ('One Piece', 'Aventura, acción', 1999, 'Monkey D. Luffy y su tripulación buscan el tesoro legendario One Piece.'),
      ('Demon Slayer', 'Acción, fantasía', 2019, 'Tanjiro emprende un viaje para salvar a su hermana y enfrentar demonios.')
    ) AS seed(titulo, genero, anio, descripcion)
    WHERE NOT EXISTS (SELECT 1 FROM animes)
  `);
}

app.get('/health', (_req, res) => res.json({ status: 'ok' }));

app.get('/api/animes', async (_req, res, next) => {
  try {
    const { rows } = await pool.query('SELECT * FROM animes ORDER BY id');
    res.json({ data: rows });
  } catch (error) { next(error); }
});

app.get('/api/animes/:id', async (req, res, next) => {
  if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: 'El id debe ser numérico' });
  try {
    const { rows } = await pool.query('SELECT * FROM animes WHERE id = $1', [req.params.id]);
    if (!rows.length) return res.status(404).json({ error: 'Anime no encontrado' });
    res.json({ data: rows[0] });
  } catch (error) { next(error); }
});

app.post('/api/animes', async (req, res, next) => {
  const { titulo, genero, anio = null, descripcion = null } = req.body || {};
  if (typeof titulo !== 'string' || !titulo.trim() || typeof genero !== 'string' || !genero.trim()) {
    return res.status(400).json({ error: 'titulo y genero son obligatorios' });
  }
  if (anio !== null && (!Number.isInteger(anio) || anio < 1900 || anio > 2100)) {
    return res.status(400).json({ error: 'anio debe ser un entero válido' });
  }
  try {
    const { rows } = await pool.query(
      'INSERT INTO animes (titulo, genero, anio, descripcion) VALUES ($1, $2, $3, $4) RETURNING *',
      [titulo.trim(), genero.trim(), anio, descripcion],
    );
    res.status(201).json({ data: rows[0] });
  } catch (error) { next(error); }
});

app.patch('/api/animes/:id', async (req, res, next) => {
  if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: 'El id debe ser numérico' });
  const { titulo, genero, anio, descripcion } = req.body || {};
  if (![titulo, genero, anio, descripcion].some((value) => value !== undefined)) {
    return res.status(400).json({ error: 'Indica al menos un campo para actualizar' });
  }
  if (titulo !== undefined && (typeof titulo !== 'string' || !titulo.trim())) return res.status(400).json({ error: 'titulo no puede estar vacío' });
  if (genero !== undefined && (typeof genero !== 'string' || !genero.trim())) return res.status(400).json({ error: 'genero no puede estar vacío' });
  if (anio !== undefined && anio !== null && (!Number.isInteger(anio) || anio < 1900 || anio > 2100)) return res.status(400).json({ error: 'anio debe ser un entero válido' });

  try {
    const { rows } = await pool.query(
      `UPDATE animes SET
         titulo = COALESCE($2, titulo), genero = COALESCE($3, genero),
         anio = CASE WHEN $4 THEN $5 ELSE anio END,
         descripcion = CASE WHEN $6 THEN $7 ELSE descripcion END
       WHERE id = $1 RETURNING *`,
      [req.params.id, titulo === undefined ? null : titulo.trim(), genero === undefined ? null : genero.trim(), anio !== undefined, anio ?? null, descripcion !== undefined, descripcion ?? null],
    );
    if (!rows.length) return res.status(404).json({ error: 'Anime no encontrado' });
    res.json({ data: rows[0] });
  } catch (error) { next(error); }
});

app.delete('/api/animes/:id', async (req, res, next) => {
  if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: 'El id debe ser numérico' });
  try {
    const { rows } = await pool.query('DELETE FROM animes WHERE id = $1 RETURNING id', [req.params.id]);
    if (!rows.length) return res.status(404).json({ error: 'Anime no encontrado' });
    res.status(204).end();
  } catch (error) { next(error); }
});

app.use((error, _req, res, _next) => {
  console.error(error);
  res.status(500).json({ error: 'Error interno del servidor' });
});

const port = Number(process.env.PORT || 3000);
initializeDatabase()
  .then(() => app.listen(port, '0.0.0.0', () => console.log(`API de anime escuchando en ${port}`)))
  .catch((error) => {
    console.error('No se pudo inicializar PostgreSQL:', error);
    process.exit(1);
  });

async function shutdown() {
  await pool.end();
  process.exit(0);
}
process.on('SIGTERM', shutdown);
process.on('SIGINT', shutdown);
